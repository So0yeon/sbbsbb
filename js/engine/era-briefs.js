/** 시대 하나의 안내. 없으면 null */
export function briefOf(worldId){ return BRIEFS[worldId] || null; }

/** 시대의 핵심 탐구질문. 없으면 null */
export function inquiryOf(worldId){
  const b = BRIEFS[worldId];
  return (b && b.inquiry) || null;
}

/** WORLDS 항목 위에 안내를 덮어씌운다 (boot.js 가 시대를 열 때 부른다) */
export function applyBrief(world, worldId){
  const b = BRIEFS[worldId];
  if (!world || !b) return world;
  if (b.brand)    world.brand = b.brand;
  if (b.title)    world.title = b.title;
  if (b.goal)     world.goal = b.goal;
  if (b.standard) world.standard = b.standard;
  if (b.body)     world.body = b.body;
  if (b.hint)     world.hint = b.hint;
  if (b.complete) world.complete = b.complete;
  if (b.inquiry)  world.inquiry = b.inquiry;
  return world;
}
