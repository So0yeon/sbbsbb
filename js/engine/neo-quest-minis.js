/* 빗살무늬토기(조사형)에 붙어 있던 낱말 적기 놀이는 뺀다.
   세우기 놀이가 그 자리를 대신한다 — 한 시대에 같은 유물로 놀이가 둘일 까닭이 없다.
   조사형의 살펴보기와 마무리 문제는 그대로 둔다. */
export const NEO_DROP_MINI = ['bitsal'];

/** 그 시대의 임무들에 이식해 온 미니게임과 그림을 덮어씌운다 */
export function applyNeoMinis(quests){
  if (!Array.isArray(quests)) return quests;

  // 새 임무를 더한다 (이미 있으면 그대로 둔다)
  NEO_EXTRA_QUESTS.forEach(x => {
    if (!quests.some(q => q && q.id === x.id)) quests.push(x);
  });

  quests.forEach(q => {
    if (!q) return;
    if (NEO_DROP_MINI.indexOf(q.id) >= 0 && q.mini) delete q.mini;
    const m = NEO_QUEST_MINIS[q.id];
    if (m) q.mini = m;
    // 사진이 있으면 사진을, 없으면 그림을 얹는다
    const img = NEO_QUEST_IMG[q.id];
    if (img && !(q.img && q.img.length)) q.img = img.slice();
    const a = NEO_QUEST_ART[q.id];
    if (a && !(q.img && q.img.length)) q.art = a;
  });
  return quests;
}
