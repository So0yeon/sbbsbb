/** 그 시대의 임무들에 이식해 온 미니게임을 덮어씌운다 */
export function applyNeoMinis(quests){
  if (!Array.isArray(quests)) return quests;
  quests.forEach(q => {
    const m = NEO_QUEST_MINIS[q && q.id];
    if (m) q.mini = m;
  });
  return quests;
}
